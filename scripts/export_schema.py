"""Emit the complete AETHRA-SEC schema as a standalone ``.sql`` file.

    python scripts/export_schema.py                  write sql/aethra_sec_schema.sql
    python scripts/export_schema.py --stdout         print it instead
    python scripts/export_schema.py --no-reference   DDL only, no reference rows

The file is generated from the same definitions the application itself uses -
``database/schema.py`` for the tables and ``database/seed.py`` for the reference
rows - so the exported SQL can never drift from what the code creates. Run this
after changing the schema and commit the result.

What the file contains:

* ``CREATE DATABASE`` and ``USE``;
* every table, in dependency order;
* the reference rows a working installation needs: roles, permissions and their
  grants, the tunable settings with their defaults, and the built-in mitigation
  knowledge base;
* the ``schema_migrations`` row recording the version this file represents.

What it deliberately does **not** contain: any user account, and any security
record - no hosts, packets, scans, findings, alerts, anomalies or incidents.
Those tables are created empty and fill only from real tool output (§1).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any, Sequence

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from aethra_sec.config.defaults import ALL_SETTING_SPECS  # noqa: E402
from aethra_sec.core.permissions import (  # noqa: E402
    PERMISSION_SPECS,
    ROLE_DEFINITIONS,
)
from aethra_sec.database.migrations import LATEST_VERSION, MIGRATIONS  # noqa: E402
from aethra_sec.database.schema import CREATE_TABLE_STATEMENTS  # noqa: E402
from aethra_sec.database.seed import _MITIGATIONS, _setting_value_to_text  # noqa: E402
from aethra_sec.version import (  # noqa: E402
    APP_NAME,
    APP_VERSION,
    AUTHORIZED_USE_NOTICE,
)

DEFAULT_OUTPUT = Path("sql") / "aethra_sec_schema.sql"

#: Default schema name; the header explains how to change it.
DEFAULT_DATABASE = "aethra_sec"


def quote(value: Any) -> str:
    """Render a Python value as a SQL literal.

    Escaping is done here rather than by string formatting elsewhere: this
    script writes a file, so there is no parameterised statement to use, and
    every literal that reaches the file passes through this one function.
    """
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "1" if value else "0"
    if isinstance(value, (int, float)):
        return str(value)
    text = str(value)
    escaped = (
        text.replace("\\", "\\\\")
        .replace("'", "''")
        .replace("\n", "\\n")
        .replace("\r", "")
        .replace("\x00", "")
    )
    return f"'{escaped}'"


def banner(title: str) -> str:
    """A section banner comment."""
    rule = "-" * 74
    return f"-- {rule}\n-- {title}\n-- {rule}"


def comment_block(text: str, width: int = 74) -> str:
    """Wrap prose into ``-- `` comment lines."""
    import textwrap

    return "\n".join(f"-- {line}" for line in textwrap.wrap(text, width))


def header(database: str) -> str:
    """File header, creation of the database, and the account guidance."""
    return f"""\
-- ===========================================================================
-- {APP_NAME} {APP_VERSION} - complete database schema
--
{comment_block(AUTHORIZED_USE_NOTICE)}
--
-- Generated by scripts/export_schema.py from the application's own schema
-- definitions. Do not edit by hand: change database/schema.py and re-run the
-- exporter, so the SQL and the code cannot disagree.
--
-- Apply it with either of:
--     mysql -u root -p < sql/aethra_sec_schema.sql
--     python scripts/init_db.py          (same schema, applied by the app)
--
-- To use a different schema name, change it in the two statements below and
-- set AETHRA_DB_NAME in your .env to match.
--
-- Contains: {len(CREATE_TABLE_STATEMENTS)} tables plus the reference rows a working installation needs
--           (roles, permissions, settings, mitigation knowledge base).
-- Contains NO user accounts and NO security records: hosts, packets, scans,
-- findings, alerts, anomalies and incidents are created empty and fill only
-- from real Nmap, PyShark and Snort output.
-- ===========================================================================

{banner("1. Database")}

CREATE DATABASE IF NOT EXISTS `{database}`
    CHARACTER SET utf8mb4
    COLLATE utf8mb4_unicode_ci;

USE `{database}`;

-- Least-privilege application account. Uncomment, set a strong password, and
-- keep that password only in .env - never in this file and never in git.
--
-- CREATE USER 'aethra_app'@'localhost' IDENTIFIED BY 'set-a-strong-password';
-- GRANT SELECT, INSERT, UPDATE, DELETE, CREATE, ALTER, INDEX, REFERENCES, DROP
--     ON `{database}`.* TO 'aethra_app'@'localhost';
-- FLUSH PRIVILEGES;
--
-- CREATE/ALTER/INDEX/REFERENCES/DROP are only needed while migrations run.
-- Afterwards SELECT, INSERT, UPDATE, DELETE is enough; start the application
-- with --no-migrate and re-grant when upgrading.

SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 1;
"""


def tables_section() -> str:
    """Every ``CREATE TABLE``, in dependency order."""
    parts = [
        banner(f"2. Tables ({len(CREATE_TABLE_STATEMENTS)}), in dependency order"),
        "",
        "-- Ordering matters: incidents and mitigation_recommendations are",
        "-- created before snort_alerts and traffic_anomalies, because those",
        "-- tables carry foreign keys into them.",
        "",
    ]
    for name, ddl in CREATE_TABLE_STATEMENTS:
        parts.append(f"-- {name}")
        parts.append(f"{ddl.strip()};")
        parts.append("")
    return "\n".join(parts)


def permissions_section() -> str:
    """Roles, permissions and the grants between them."""
    lines = [
        banner("3. Roles, permissions and grants"),
        "",
        "-- The authorisation model. ADMIN holds every permission; USER holds",
        "-- the monitoring, assessment and reporting subset.",
        "",
    ]

    lines.append("INSERT INTO permissions (code, name, description, category) VALUES")
    values = [
        f"    ({quote(spec.code)}, {quote(spec.name)}, "
        f"{quote(spec.description)}, {quote(spec.category)})"
        for spec in PERMISSION_SPECS
    ]
    lines.append(",\n".join(values))
    lines.append(
        "ON DUPLICATE KEY UPDATE name = VALUES(name), "
        "description = VALUES(description), category = VALUES(category);"
    )
    lines.append("")

    lines.append("INSERT INTO roles (name, description, created_at) VALUES")
    role_values = [
        f"    ({quote(name)}, {quote(definition['description'])}, UTC_TIMESTAMP(6))"
        for name, definition in ROLE_DEFINITIONS.items()
    ]
    lines.append(",\n".join(role_values))
    lines.append("ON DUPLICATE KEY UPDATE description = VALUES(description);")
    lines.append("")

    for role_name, definition in ROLE_DEFINITIONS.items():
        codes: Sequence[str] = tuple(definition["permissions"])  # type: ignore[arg-type]
        if not codes:
            continue
        lines.append(f"-- {role_name}: {len(codes)} permission(s)")
        lines.append(
            "INSERT INTO role_permissions (role_id, permission_id, granted_at)\n"
            "SELECT r.id, p.id, UTC_TIMESTAMP(6)\n"
            "FROM roles r\n"
            "JOIN permissions p ON p.code IN (\n"
            + ",\n".join(f"    {quote(code)}" for code in codes)
            + "\n)\n"
            f"WHERE r.name = {quote(role_name)}\n"
            "ON DUPLICATE KEY UPDATE granted_at = role_permissions.granted_at;"
        )
        lines.append("")
    return "\n".join(lines)


def settings_section() -> str:
    """The tunable settings with their documented defaults."""
    lines = [
        banner(f"4. Tunable settings ({len(ALL_SETTING_SPECS)})"),
        "",
        "-- Detection thresholds, correlation, capture, retention, interface,",
        "-- security policy and notification settings. Every one is editable on",
        "-- the Settings screen; the values here are the documented defaults.",
        "",
        "INSERT INTO system_settings "
        "(setting_key, setting_value, value_type, category, description, updated_at)"
        " VALUES",
    ]
    values = []
    for spec in ALL_SETTING_SPECS:
        rendered = _setting_value_to_text(spec.default, spec.value_type)
        values.append(
            f"    ({quote(spec.key)}, {quote(rendered)}, {quote(spec.value_type)}, "
            f"{quote(spec.category)}, {quote(spec.description)}, UTC_TIMESTAMP(6))"
        )
    lines.append(",\n".join(values))
    lines.append(
        "ON DUPLICATE KEY UPDATE description = VALUES(description), "
        "category = VALUES(category), value_type = VALUES(value_type);"
    )
    lines.append("")
    return "\n".join(lines)


def mitigation_section() -> str:
    """The built-in mitigation knowledge base and its threat mapping."""
    lines = [
        banner(f"5. Mitigation knowledge base ({len(_MITIGATIONS)} entries)"),
        "",
        "-- Guidance text, not security data. Each entry explains what the",
        "-- detection means, why it matters, what to do now, what to do long",
        "-- term, and how to verify it worked. AETHRA-SEC never applies any of",
        "-- it automatically - every recommendation is for an authorised human",
        "-- to decide on.",
        "",
    ]
    for entry in _MITIGATIONS:
        source = entry["source"]
        lines.append(f"-- {entry['code']}: {entry['threat_name']}")
        lines.append(
            "INSERT INTO mitigation_recommendations\n"
            "    (code, threat_name, category, severity, applies_to_service,\n"
            "     detection_source, explanation, why_it_matters, immediate_action,\n"
            "     long_term_action, verification_steps, reference_notes,\n"
            "     is_active, is_builtin, created_at, updated_at)\n"
            "VALUES (\n"
            f"    {quote(entry['code'])}, {quote(entry['threat_name'])},\n"
            f"    {quote(str(entry['category']))}, {quote(str(entry['severity']))},\n"
            f"    {quote(entry['service'])}, {quote(str(source) if source else '')},\n"
            f"    {quote(entry['explanation'])},\n"
            f"    {quote(entry['why'])},\n"
            f"    {quote(entry['immediate'])},\n"
            f"    {quote(entry['long_term'])},\n"
            f"    {quote(entry['verify'])},\n"
            "    '', 1, 1, UTC_TIMESTAMP(6), UTC_TIMESTAMP(6)\n"
            ")\n"
            "ON DUPLICATE KEY UPDATE updated_at = mitigation_recommendations.updated_at;"
        )
        lines.append(
            "INSERT INTO threat_mitigation_mapping\n"
            "    (category, recommendation_id, priority, condition_service,\n"
            "     condition_min_severity, is_active)\n"
            f"SELECT {quote(str(entry['category']))}, id, "
            f"{10 if entry['service'] else 100}, {quote(entry['service'])}, '', 1\n"
            f"FROM mitigation_recommendations WHERE code = {quote(entry['code'])}\n"
            "ON DUPLICATE KEY UPDATE priority = VALUES(priority);"
        )
        lines.append("")
    return "\n".join(lines)


def migrations_section() -> str:
    """Record the schema version this file represents."""
    lines = [
        banner("6. Schema version"),
        "",
        "-- Recorded so the application does not re-apply a migration this file",
        "-- already contains. Keep it in step with database/migrations.py.",
        "",
        "INSERT INTO schema_migrations (version, name, applied_at) VALUES",
    ]
    values = [
        f"    ({migration.version}, {quote(migration.name)}, UTC_TIMESTAMP(6))"
        for migration in MIGRATIONS
    ]
    lines.append(",\n".join(values))
    lines.append("ON DUPLICATE KEY UPDATE name = VALUES(name);")
    lines.append("")
    lines.append(
        f"-- Schema version {LATEST_VERSION}. After applying this file, create the\n"
        "-- first administrator with:  python scripts/create_admin.py"
    )
    lines.append("")
    return "\n".join(lines)


def build_sql(database: str, *, reference_data: bool = True) -> str:
    """Assemble the whole file."""
    sections = [header(database), "", tables_section()]
    if reference_data:
        sections.extend(
            [
                permissions_section(),
                settings_section(),
                mitigation_section(),
                migrations_section(),
            ]
        )
    else:
        sections.append(
            "-- Reference rows were omitted (--no-reference). Run\n"
            "-- 'python scripts/init_db.py' to seed roles, permissions,\n"
            "-- settings and the mitigation knowledge base.\n"
        )
    return "\n".join(sections).rstrip() + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    """Write (or print) the SQL file."""
    parser = argparse.ArgumentParser(
        prog="export_schema",
        description="Export the AETHRA-SEC schema as a standalone .sql file.",
    )
    parser.add_argument(
        "--output", default=str(DEFAULT_OUTPUT), help="file to write"
    )
    parser.add_argument(
        "--database", default=DEFAULT_DATABASE, help="schema name to create"
    )
    parser.add_argument("--stdout", action="store_true", help="print instead of writing")
    parser.add_argument(
        "--no-reference", action="store_true",
        help="emit the tables only, without the reference rows",
    )
    arguments = parser.parse_args(argv)

    sql = build_sql(arguments.database, reference_data=not arguments.no_reference)
    if arguments.stdout:
        print(sql)
        return 0

    path = Path(arguments.output)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(sql, encoding="utf-8")
    print(
        f"Wrote {path} - {len(CREATE_TABLE_STATEMENTS)} tables, "
        f"{len(PERMISSION_SPECS)} permissions, {len(ALL_SETTING_SPECS)} settings, "
        f"{len(_MITIGATIONS)} mitigation entries, {len(sql.splitlines()):,} lines."
    )
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
