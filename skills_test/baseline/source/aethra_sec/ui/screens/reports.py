"""Reporting screen (§48-§50, §95).

Reports are built from stored records only. The preview shows exactly how many
records each section covers *before* anything is written, so an operator can
see when a report would be empty rather than discovering it afterwards.
"""

from __future__ import annotations

import tkinter as tk
from datetime import timedelta
from tkinter import ttk
from typing import Any

from aethra_sec.core.events import Event, EventType
from aethra_sec.models.enums import ExportFormat, ReportType
from aethra_sec.models.system import ReportRecord
from aethra_sec.reports.builder import ReportDocument
from aethra_sec.ui import dispatch
from aethra_sec.ui.base import Screen
from aethra_sec.ui.theme import PALETTE, configure_text_widget
from aethra_sec.ui.widgets import (
    Card,
    Column,
    DataTable,
    Toolbar,
    show_message,
)
from aethra_sec.utils.formatting import format_bytes, format_count
from aethra_sec.utils.timeutil import format_local, utcnow

HISTORY_COLUMNS = (
    Column("generated", "Generated", width=150),
    Column("type", "Report", width=200),
    Column("format", "Format", width=70),
    Column("period", "Period", width=210),
    Column("records", "Records", width=80, anchor="e"),
    Column("size", "Size", width=85, anchor="e"),
    Column("by", "Generated by", width=120),
    Column("path", "File", width=330, stretch=True),
)

PERIODS: dict[str, timedelta | None] = {
    "Last 24 hours": timedelta(hours=24),
    "Last 7 days": timedelta(days=7),
    "Last 30 days": timedelta(days=30),
    "Last 90 days": timedelta(days=90),
    "All time": None,
}


class ReportsScreen(Screen):
    """Generate and export reports from real records."""

    title = "Reports"
    subtitle = "Generated from stored records only - every figure is traceable"
    required_permission = "report.generate"

    def __init__(self, parent: tk.Misc, app: Any) -> None:
        """Create the screen."""
        super().__init__(parent, app)
        self._preview: ReportDocument | None = None

    # ------------------------------------------------------------------
    # Layout
    # ------------------------------------------------------------------
    def build(self) -> None:
        """Construct the reporting screen."""
        controls = Card(self, "Generate a report", fonts=self.fonts, padding=12)
        controls.pack(fill="x")

        row = ttk.Frame(controls, style="Card.TFrame")
        row.pack(fill="x")

        ttk.Label(row, text="Report type", style="CardMuted.TLabel").pack(side="left")
        self._type_var = tk.StringVar(value=ReportType.SECURITY_ASSESSMENT.label)
        ttk.Combobox(
            row, textvariable=self._type_var, state="readonly", width=34,
            values=[report.label for report in ReportType],
        ).pack(side="left", padx=(8, 14))

        ttk.Label(row, text="Period", style="CardMuted.TLabel").pack(side="left")
        self._period_var = tk.StringVar(value="Last 7 days")
        ttk.Combobox(
            row, textvariable=self._period_var, state="readonly", width=15,
            values=list(PERIODS),
        ).pack(side="left", padx=(8, 14))

        ttk.Label(row, text="Scope", style="CardMuted.TLabel").pack(side="left")
        self._scope_var = tk.StringVar(value="All monitored assets")
        ttk.Entry(row, textvariable=self._scope_var, width=26).pack(
            side="left", padx=(8, 14)
        )

        ttk.Button(
            row, text="Preview", style="Ghost.TButton", command=self._generate_preview
        ).pack(side="left", padx=(0, 6))
        for label, export_format in (
            ("Export PDF", ExportFormat.PDF),
            ("Export Excel", ExportFormat.XLSX),
            ("Export CSV", ExportFormat.CSV),
        ):
            ttk.Button(
                row, text=label, style="Accent.TButton",
                command=lambda f=export_format: self._generate(f),
            ).pack(side="left", padx=(0, 6))

        self._output_label = ttk.Label(controls, text="", style="CardDim.TLabel")
        self._output_label.pack(anchor="w", pady=(8, 0))

        panes = ttk.PanedWindow(self, orient="vertical")
        panes.pack(fill="both", expand=True, pady=(10, 0))

        preview_host = ttk.Frame(panes, style="TFrame")
        panes.add(preview_host, weight=3)
        preview_card = Card(preview_host, "Preview", fonts=self.fonts, padding=12)
        preview_card.pack(fill="both", expand=True)
        self._preview_text = tk.Text(preview_card, wrap="word")
        configure_text_widget(self._preview_text, self.fonts)
        scrollbar = ttk.Scrollbar(
            preview_card, orient="vertical", command=self._preview_text.yview
        )
        self._preview_text.configure(yscrollcommand=scrollbar.set)
        self._preview_text.insert(
            "1.0",
            "Choose a report type and period, then select Preview to see which "
            "records the report would cover before exporting it.",
        )
        self._preview_text.configure(state="disabled")
        self._preview_text.pack(side="left", fill="both", expand=True)
        scrollbar.pack(side="right", fill="y")

        history_host = ttk.Frame(panes, style="TFrame")
        panes.add(history_host, weight=2)
        history_card = Card(
            history_host, "Report history", subtitle="who generated what, and when",
            fonts=self.fonts, padding=12,
        )
        history_card.pack(fill="both", expand=True)
        toolbar = Toolbar(history_card)
        toolbar.pack(fill="x", pady=(0, 6))
        toolbar.add_button("Refresh", self._load_history)
        toolbar.add_button("Open output folder path", self._show_output_dir)
        self._history_table = DataTable(history_card, HISTORY_COLUMNS, height=7)
        self._history_table.pack(fill="both", expand=True)

    # ------------------------------------------------------------------
    # Data
    # ------------------------------------------------------------------
    def on_show(self) -> None:
        """Show the output directory and load history."""
        reports = self.context.reports
        if reports is not None:
            self._output_label.configure(
                text=f"Reports are written to: {reports.output_dir}"
            )
        self._load_history()

    def _selected_type(self) -> ReportType:
        """The report type matching the current selection."""
        label = self._type_var.get()
        return next(
            (report for report in ReportType if report.label == label),
            ReportType.SECURITY_ASSESSMENT,
        )

    def _period_start(self):
        """Start of the selected period, or ``None`` for all time."""
        delta = PERIODS.get(self._period_var.get())
        return utcnow() - delta if delta else None

    def _generate_preview(self) -> None:
        """Build the report in memory and show its record counts."""
        reports = self.context.reports
        session = self.session
        if reports is None or session is None:
            return
        # Tk variables must only be read on the Tk thread, so the parameters
        # are captured here and the worker closes over plain values.
        report_type = self._selected_type()
        period_start = self._period_start()
        scope = self._scope_var.get().strip() or "All monitored assets"
        self.status(f"Building {report_type.label} preview...")
        self.run_async(
            lambda: reports.preview(
                session, report_type, period_start=period_start, scope=scope
            ),
            self._render_preview,
            name="report-preview",
        )

    def _render_preview(self, document: ReportDocument) -> None:
        """Render the preview text."""
        self._preview = document
        lines = [f"{document.title}", "=" * len(document.title), ""]
        for label, value in document.metadata_rows():
            lines.append(f"{label:<16}: {value}")
        lines.append("")

        if document.highlights:
            lines.append("SUMMARY")
            for label, value in document.highlights:
                lines.append(f"  {label:<32} {value}")
            lines.append("")

        lines.append("SECTIONS")
        for section in document.sections:
            marker = (
                f"{section.row_count:>6,} record(s)"
                if section.has_rows
                else "        no records"
            )
            lines.append(f"  {marker}   {section.title}")
        lines.append("")

        if document.observations:
            lines.append("OBSERVATIONS")
            lines.extend(f"  - {note}" for note in document.observations)
            lines.append("")

        lines.append("CONCLUSION")
        lines.append(document.conclusion)
        lines.append("")

        for section in document.sections:
            lines.append(f"--- {section.title} ---")
            lines.append("  " + " | ".join(section.columns))
            if section.has_rows:
                for row in section.rows[:12]:
                    lines.append("  " + " | ".join(str(cell) for cell in row))
                if section.row_count > 12:
                    lines.append(f"  ... {section.row_count - 12:,} more row(s)")
            else:
                lines.append("  No records available for this section.")
            lines.append("")

        self._preview_text.configure(state="normal")
        self._preview_text.delete("1.0", "end")
        self._preview_text.insert("1.0", "\n".join(lines))
        self._preview_text.configure(state="disabled")
        self.status(
            f"{document.title}: {document.total_records:,} record(s) across "
            f"{len(document.sections)} section(s)."
        )

    def _generate(self, export_format: ExportFormat) -> None:
        """Generate and write a report."""
        reports = self.context.reports
        session = self.session
        if reports is None or session is None:
            return
        report_type = self._selected_type()
        period_start = self._period_start()
        scope = self._scope_var.get().strip() or "All monitored assets"
        self.status(f"Generating {report_type.label} ({export_format})...")
        reports.generate_async(
            session, report_type, export_format,
            self._on_generated,
            period_start=period_start,
            scope=scope,
        )

    def _on_generated(self, record: ReportRecord | None, error: str) -> None:
        """Report the outcome back on the Tk thread."""
        def deliver() -> None:
            if not self.is_alive:
                return
            if record is None:
                self.status("Report generation failed.")
                self.show_error_message(error, "Report generation failed")
                return
            total = sum(record.record_counts.values())
            show_message(
                self, "Report generated",
                f"{record.title} ({record.export_format})",
                detail=(
                    f"Records covered: {total:,}\n"
                    f"File: {record.file_path}\n"
                    f"Size: {format_bytes(record.file_size_bytes)}\n"
                    f"Period: {format_local(record.period_start)} to "
                    f"{format_local(record.period_end)}\n"
                    f"Generated by: {record.generated_by_username or 'unknown'}\n\n"
                    + (
                        "This report contains no records: the selected period "
                        "and scope matched nothing in the database."
                        if total == 0
                        else "Every figure in this report comes from stored records."
                    )
                ),
                fonts=self.fonts,
            )
            self.status(f"Report written to {record.file_path}")
            self._load_history()

        # Posted rather than scheduled with after(): this runs on the export
        # worker, and Tk may only be touched from its own thread.
        dispatch.post(deliver)

    def _load_history(self) -> None:
        """Reload the report history (§95)."""
        reports = self.context.reports
        session = self.session
        if reports is None or session is None:
            return
        self.run_async(
            lambda: reports.history(session, limit=200),
            self._apply_history,
            name="report-history",
        )

    def _apply_history(self, records: list[ReportRecord]) -> None:
        """Render the report history table."""
        self._history_table.set_rows(
            [
                {
                    "generated": format_local(record.generated_at),
                    "type": record.report_type.label,
                    "format": str(record.export_format),
                    "period": (
                        f"{format_local(record.period_start, '%d %b %H:%M')} - "
                        f"{format_local(record.period_end, '%d %b %H:%M')}"
                    ),
                    "records": format_count(sum(record.record_counts.values())),
                    "size": format_bytes(record.file_size_bytes),
                    "by": record.generated_by_username or "-",
                    "path": record.file_path,
                }
                for record in records
            ]
        )
        self.status(
            f"{len(records)} report(s) generated previously."
            if records
            else "No reports have been generated yet."
        )

    def _show_output_dir(self) -> None:
        """Show the configured report output directory."""
        reports = self.context.reports
        if reports is None:
            return
        show_message(
            self, "Report output folder", str(reports.output_dir),
            detail=(
                "Change this on the Settings screen or with AETHRA_REPORT_DIR "
                "in the configuration file."
            ),
            fonts=self.fonts,
        )

    def handle_event(self, event: Event) -> None:
        """Refresh history when a report is generated elsewhere."""
        if event.type == EventType.REPORT_GENERATED:
            self._load_history()
